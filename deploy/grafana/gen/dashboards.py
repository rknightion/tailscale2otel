"""The dashboard family: what dashboards exist, and what is on each (#526).

Before #526 `build.py` hardcoded one dashboard and carried the domain/leaf
arrangement in module-level constants. That made the split structurally
impossible and, worse, made the coverage gate structurally wrong: a gate scoped
to one artifact reports a metric as missing the moment its panel moves to the
other file. Everything that knows a dashboard EXISTS lives here now, so both are
built in one process and the coverage union is computed across both.

The two dashboards answer different questions, which is the whole point of the
split:

  tailscale2otel-tailnet  "is my tailnet healthy?"   — fleet, flows, policy, audit
  tailscale2otel-health   "is the exporter healthy?" — collection, ingestion,
                                                       delivery, runtime, cost

Neither uid may be the bare "tailscale2otel": that belongs to the alerts FOLDER
(deploy/alerts/grafana-managed/_folder.json), which is why the single dashboard
was called "-overview" in the first place.
"""

